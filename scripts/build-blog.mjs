// Turns the articles in content/blog/*.md (YAML frontmatter + Markdown) into lib/blog/posts.generated.ts,
// so the blog pages import them like code: no file reads at request time (the Cloudflare build has no disk).
// Editor notes left as HTML comments (<!-- VERIFY … -->, <!-- SCREENSHOT … -->) are stripped here and never ship.
// Run: node scripts/build-blog.mjs  (the build and dev scripts run it first).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'content', 'blog');
const outFile = join(root, 'lib', 'blog', 'posts.generated.ts');

const REQUIRED = ['title', 'slug', 'description', 'primary_keyword', 'cluster', 'pillar', 'published', 'updated', 'faq'];

const posts = readdirSync(sourceDir)
  .filter((name) => /^\d+-.+\.md$/.test(name))
  .sort()
  .map((name) => {
    const text = readFileSync(join(sourceDir, name), 'utf8').replace(/\r\n/g, '\n');
    const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!match) throw new Error(`${name}: no frontmatter`);
    const data = parse(match[1]);
    for (const key of REQUIRED) if (!data[key]) throw new Error(`${name}: frontmatter is missing "${key}"`);
    if (!name.endsWith(`-${data.slug}.md`)) throw new Error(`${name}: file name does not end with the slug "${data.slug}"`);

    let body = match[2].replace(/<!--[\s\S]*?-->/g, '');
    // The page renders the H1 and the date itself.
    const heading = body.match(/^# (.+)$/m)?.[1].trim() ?? data.title;
    body = body.replace(/^# .+$/m, '').replace(/^\*Last updated:[^*]*\*\s*$/m, '');
    body = body.replace(/\n{3,}/g, '\n\n').trim();

    return {
      number: Number(name.slice(0, name.indexOf('-'))),
      slug: data.slug,
      title: data.title,
      heading,
      description: data.description,
      primaryKeyword: data.primary_keyword,
      secondaryKeywords: data.secondary_keywords ?? [],
      cluster: data.cluster,
      pillar: data.pillar,
      author: String(data.author ?? ''),
      comparesTools: data.compares_tools === true,
      published: String(data.published),
      updated: String(data.updated),
      faq: data.faq.map(({ q, a }) => ({ q, a })),
      body,
    };
  });

const slugs = new Set(posts.map((post) => post.slug));
if (slugs.size !== posts.length) throw new Error('Two articles share a slug');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/build-blog.mjs from content/blog/*.md. Do not edit; edit the Markdown and rerun the script.\n` +
    `import type { BlogPostSource } from './types';\n\n` +
    `export const POSTS: BlogPostSource[] = ${JSON.stringify(posts, null, 2)};\n`,
);
console.log(`blog: ${posts.length} articles -> ${outFile.slice(root.length + 1)}`);

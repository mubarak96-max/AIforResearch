// Turns the articles in content/blog/*.md (YAML frontmatter + Markdown) into lib/blog/posts.generated.ts,
// so the blog pages import them like code: no file reads at request time (the Cloudflare build has no disk).
// Editor notes left as HTML comments (<!-- VERIFY … -->, <!-- SCREENSHOT … -->) are stripped here and never ship.
// Run: node scripts/build-blog.mjs  (the build and dev scripts run it first).
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'content', 'blog');
const outFile = join(root, 'lib', 'blog', 'posts.generated.ts');

const REQUIRED = ['title', 'slug', 'description', 'primary_keyword', 'cluster', 'pillar', 'published', 'updated', 'faq'];

const posts = readdirSync(sourceDir)
  .filter((name) => /^\d+-.+\.md$/.test(name))
  .sort()
  .map((name) => {
    const text = readFileSync(join(sourceDir, name), 'utf8').replace(/\r\n/g, '\n');
    const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!match) throw new Error(`${name}: no frontmatter`);
    const data = parse(match[1]);
    for (const key of REQUIRED) if (!data[key]) throw new Error(`${name}: frontmatter is missing "${key}"`);
    if (!name.endsWith(`-${data.slug}.md`)) throw new Error(`${name}: file name does not end with the slug "${data.slug}"`);

    let body = match[2].replace(/<!--[\s\S]*?-->/g, '');
    // The page renders the H1 and the date itself.
    const heading = body.match(/^# (.+)$/m)?.[1].trim() ?? data.title;
    body = body.replace(/^# .+$/m, '').replace(/^\*Last updated:[^*]*\*\s*$/m, '');
    body = body.replace(/\n{3,}/g, '\n\n').trim();

    return {
      number: Number(name.slice(0, name.indexOf('-'))),
      slug: data.slug,
      title: data.title,
      heading,
      description: data.description,
      primaryKeyword: data.primary_keyword,
      secondaryKeywords: data.secondary_keywords ?? [],
      cluster: data.cluster,
      pillar: data.pillar,
      author: String(data.author ?? ''),
      comparesTools: data.compares_tools === true,
      published: String(data.published),
      updated: String(data.updated),
      faq: data.faq.map(({ q, a }) => ({ q, a })),
      body,
    };
  });

const slugs = new Set(posts.map((post) => post.slug));
if (slugs.size !== posts.length) throw new Error('Two articles share a slug');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/build-blog.mjs from content/blog/*.md. Do not edit; edit the Markdown and rerun the script.\n` +
    `import type { BlogPostSource } from './types';\n\n` +
    `export const POSTS: BlogPostSource[] = ${JSON.stringify(posts, null, 2)};\n`,
);
console.log(`blog: ${posts.length} articles -> ${outFile.slice(root.length + 1)}`);

// ------------------------------------------------------------------ landing pages
// content/pages/<section>/<slug>.md -> lib/pages.generated.ts. Long-form landing pages (audience,
// feature, alternatives, templates): frontmatter for the hero, FAQ and links, Markdown for the body.

const pagesDir = join(root, 'content', 'pages');
const pagesOut = join(root, 'lib', 'pages.generated.ts');
const SECTIONS = ['for', 'features', 'alternatives', 'templates'];
const PAGE_REQUIRED = ['slug', 'seo_title', 'description', 'heading', 'intro', 'primary_keyword', 'hero', 'cta', 'faq', 'updated'];

const pages = [];
for (const section of SECTIONS) {
  const dir = join(pagesDir, section);
  if (!existsSync(dir)) continue;
  for (const name of readdirSync(dir).filter((file) => file.endsWith('.md')).sort()) {
    const text = readFileSync(join(dir, name), 'utf8').replace(/\r\n/g, '\n');
    const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!match) throw new Error(`pages/${section}/${name}: no frontmatter`);
    const data = parse(match[1]);
    for (const key of PAGE_REQUIRED) if (!data[key]) throw new Error(`pages/${section}/${name}: frontmatter is missing "${key}"`);
    if (name !== `${data.slug}.md`) throw new Error(`pages/${section}/${name}: file name is not the slug "${data.slug}"`);
    if (!['ask', 'cta'].includes(data.hero)) throw new Error(`pages/${section}/${name}: hero must be "ask" or "cta"`);
    if (!data.cta.label || !data.cta.href) throw new Error(`pages/${section}/${name}: cta needs label and href`);
    pages.push({
      section,
      slug: data.slug,
      seoTitle: data.seo_title,
      description: data.description,
      heading: data.heading,
      intro: data.intro,
      primaryKeyword: data.primary_keyword,
      secondaryKeywords: data.secondary_keywords ?? [],
      hero: data.hero,
      cta: { label: data.cta.label, href: data.cta.href },
      planNote: data.plan_note ?? '',
      related: data.related ?? [],
      updated: String(data.updated),
      faq: data.faq.map(({ q, a }) => ({ q, a })),
      body: match[2].replace(/<!--[\s\S]*?-->/g, '').replace(/\n{3,}/g, '\n\n').trim(),
    });
  }
}
writeFileSync(
  pagesOut,
  `// Generated by scripts/build-blog.mjs from content/pages/<section>/*.md. Do not edit.\n` +
    `import type { LandingPageSource } from './landingPages';\n\n` +
    `export const LANDING_PAGES: LandingPageSource[] = ${JSON.stringify(pages, null, 2)};\n`,
);
console.log(`pages: ${pages.length} landing pages -> ${pagesOut.slice(root.length + 1)}`);
